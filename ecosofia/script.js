const criarCardInicioHTML = (item) => { // monta o HTML de um card da página inicial 
    let spanHTML = "";
    if (item.destaque !== "") {
        if (item.linkDestaque !== "") {
            spanHTML = `<span><a href="${item.linkDestaque}">${item.destaque}</a></span>`;
        } else {
            spanHTML = `<span>${item.destaque}</span>`;
        }
    }

    return `
        <section class="paragrafo">
            <div>
                <h2>${item.titulo}</h2>
                <p>${item.texto} ${spanHTML}</p>
            </div>
            <figure>
                <img src="${item.imagem}" alt="${item.alt}">
                <figcaption>${item.legenda}</figcaption>
            </figure>
        </section>
    `;
};

