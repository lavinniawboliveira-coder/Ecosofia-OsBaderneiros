// Função que envolve a palavra encontrada em uma tag <span>
function destacarTexto(texto, termo) {
    if (!termo) return texto; // Se a busca estiver vazia, retorna o texto normal
    // Cria uma expressão regular ignorando maiúsculas/minúsculas ('gi')
    const regex = new RegExp(`(${termo})`, "gi");
    return texto.replace(regex, `<span class="destaque-busca">${termo}</span>`);
}

function configurarPesquisa() {
    const caixaPesquisa = document.getElementById("caixaPesquisa");
    const areaPrincipal = document.querySelector("main");

    // Se a página atual não tiver barra de pesquisa ou <main>, não faz nada
    if (!caixaPesquisa || !areaPrincipal) 
    {
        return;
    }

    // Seleciona todos os elementos de texto dentro do <main> (exceto o título principal h1)
    const elementosTexto = Array.from(
        areaPrincipal.querySelectorAll("h2, p, figcaption")
    );

    // Salva o HTML original de cada elemento para restaurar quando apagar a busca
    const conteudosOriginais = elementosTexto.map((elemento) => ({
        elemento: elemento,
        htmlOriginal: elemento.innerHTML
    }));

    caixaPesquisa.addEventListener("input", (evento) => {
        const termo = evento.target.value.trim();
        const termoMinusculo = termo.toLowerCase();

        // restaura todo o texto ao estado original 
        conteudosOriginais.forEach((item) => {
            item.elemento.innerHTML = item.htmlOriginal;
        });

        // Se a barra estiver vazia, encerra por aqui
        if (termo === "") {
            return
        };

        // Usa .filter() e .includes() para encontrar apenas os elementos que têm a palavra
        const elementosEncontrados = conteudosOriginais.filter((item) =>
            item.elemento.textContent.toLowerCase().includes(termoMinusculo)
        );

        // Cria a expressão regular evitando alterar o que está dentro de tags HTML (ex: href="...")
        const regex = new RegExp(`(${termo})(?![^<]*>)`, "gi");

        // Aplica o destaque <span> apenas nos elementos filtrados
        elementosEncontrados.forEach((item) => {
            item.elemento.innerHTML = item.htmlOriginal.replace(
                regex,
                `<span class="destaque-busca">$1</span>`
            );
        });
    });
}
configurarPesquisa();

// === Menu hambúrguer responsivo ===
function configurarMenuMobile() {
    const btnMenu = document.getElementById("btn-menu");
    const nav = document.querySelector("header nav");

    if (!btnMenu || !nav) return;

    // Abre ou fecha o menu ao clicar no botão hambúrguer
    btnMenu.addEventListener("click", () => {
        nav.classList.toggle("ativo");

        // Atualiza acessibilidade (true quando aberto, false quando fechado)
        const estaAberto = nav.classList.contains("ativo");
        btnMenu.setAttribute("aria-expanded", estaAberto);
    });

    // Fecha o menu automaticamente ao clicar em qualquer link dele
    const linksMenu = nav.querySelectorAll("a");
    linksMenu.forEach((link) => {
        link.addEventListener("click", () => {
            nav.classList.remove("ativo");
            btnMenu.setAttribute("aria-expanded", "false");
        });
    });
}
configurarMenuMobile();

